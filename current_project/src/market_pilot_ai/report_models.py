"""
MarketPilot AI - Structured Research Report Models

Pydantic models for the final validated MarketPilot
research report.
"""

from pydantic import BaseModel, Field


class MarketOverview(BaseModel):
    summary: str


class TechnicalReport(BaseModel):
    summary: str
    trend: str
    unified_signal: str
    signal_consistency: str
    rsi_comment: str
    volatility_comment: str


class FundamentalReport(BaseModel):
    summary: str
    valuation_comment: str
    profitability_comment: str


class RiskReport(BaseModel):
    summary: str
    risk_level: str
    important_risks: list[str]


class NewsReport(BaseModel):
    summary: str
    sentiment: str
    important_events: list[str]


class ScoreComponent(BaseModel):
    """
    One deterministic score component.
    """

    score: float = Field(
        ge=0,
        le=100,
    )

    weight: float = Field(
        ge=0,
        le=1,
    )

    contribution: float


class ScoreBreakdown(BaseModel):
    """
    Transparent deterministic score breakdown.
    """

    market: ScoreComponent
    technical: ScoreComponent
    fundamental: ScoreComponent
    risk: ScoreComponent
    news: ScoreComponent


class ScoreReport(BaseModel):
    summary: str

    # Deterministic score.
    deterministic_score: float

    # Independent AI score.
    ai_score: float

    # AI - deterministic.
    score_difference: float | None

    # High / Moderate / Low / Unavailable.
    score_agreement: str

    # Individual deterministic components.
    score_breakdown: ScoreBreakdown


class SignalReport(BaseModel):
    """
    Unified market signal generated by the
    deterministic signal-reconciliation layer.
    """

    market_signal: str
    technical_signal: str
    unified_signal: str
    signal_consistency: str


class ResearchReport(BaseModel):
    """
    Complete validated MarketPilot research report.
    """

    symbol: str

    market_overview: MarketOverview

    technical_analysis: TechnicalReport

    fundamental_analysis: FundamentalReport

    risk_analysis: RiskReport

    news_analysis: NewsReport

    signal_analysis: SignalReport

    score_interpretation: ScoreReport

    research_takeaway: str